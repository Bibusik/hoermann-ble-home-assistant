static const char *DEVICE_ID = "hoermann_gate";
static const char *CMD_TOPIC_PREFIX = "hoermann/gate/cmd/";
static const char *AVAIL_TOPIC = "hoermann/gate/status";

struct ChannelDef {
  const char *slug;
  const char *name;
  uint16_t cmd;
};
static const ChannelDef CHANNELS[] = {
    {"impuls", "Impuls", CMD_CHANNEL_1},
    {"light", "Light", CMD_CHANNEL_2_LIGHT},
    {"partial", "Open Partial (1/2)", CMD_CHANNEL_3},
    {"open", "Open", CMD_CHANNEL_4},
    {"close", "Close", CMD_CHANNEL_5},
    {"ventilation", "Ventilation Position", CMD_CHANNEL_6},
};
static const size_t CHANNEL_COUNT = sizeof(CHANNELS) / sizeof(CHANNELS[0]);

void publishHADiscovery() {
  for (size_t i = 0; i < CHANNEL_COUNT; i++) {
    char topic[160], payload[400], cmdTopic[96], uid[64];
    snprintf(cmdTopic, sizeof(cmdTopic), "%s%s", CMD_TOPIC_PREFIX, CHANNELS[i].slug);
    snprintf(uid, sizeof(uid), "%s_%s", DEVICE_ID, CHANNELS[i].slug);
    snprintf(topic, sizeof(topic), "homeassistant/button/%s/config", uid);
    snprintf(payload, sizeof(payload),
             "{\"name\":\"%s\",\"uniq_id\":\"%s\",\"cmd_t\":\"%s\",\"avty_t\":\"%s\","
             "\"dev\":{\"ids\":[\"%s\"],\"name\":\"Hoermann Gate\",\"mf\":\"DIY\"}}",
             CHANNELS[i].name, uid, cmdTopic, AVAIL_TOPIC, DEVICE_ID);
    mqtt.publish(topic, payload, true);
  }
  // one extra button to (re-)register a key while the gate is in pairing mode
  char uid[64], cmdTopic[96], topic[160], payload[400];
  snprintf(uid, sizeof(uid), "%s_register", DEVICE_ID);
  snprintf(cmdTopic, sizeof(cmdTopic), "%sregister", CMD_TOPIC_PREFIX);
  snprintf(topic, sizeof(topic), "homeassistant/button/%s/config", uid);
  snprintf(payload, sizeof(payload),
           "{\"name\":\"Register new key\",\"uniq_id\":\"%s\",\"cmd_t\":\"%s\",\"avty_t\":\"%s\","
           "\"dev\":{\"ids\":[\"%s\"],\"name\":\"Hoermann Gate\",\"mf\":\"DIY\"}}",
           uid, cmdTopic, AVAIL_TOPIC, DEVICE_ID);
  mqtt.publish(topic, payload, true);

  mqtt.publish(AVAIL_TOPIC, "online", true);
}

// PubSubClient callbacks must return quickly - registerNewRootKey() can run
// for 1-2+ minutes (several BLE reconnect attempts, each waiting up to ~22s).
// Running that directly inside the callback starved the main loop() for too
// long and the board rebooted. Defer it: just set a flag here, and run the
// actual registration from loop(), where we can call mqtt.loop()/yield()
// between BLE attempts to keep MQTT and the watchdog happy.
volatile bool gRegisterRequested = false;

void onMqttMessage(char *topic, byte *payload, unsigned int length) {
  String t(topic);
  if (!t.startsWith(CMD_TOPIC_PREFIX)) return;
  String slug = t.substring(strlen(CMD_TOPIC_PREFIX));

  if (slug == "register") {
    gRegisterRequested = true;
    return;
  }
  for (size_t i = 0; i < CHANNEL_COUNT; i++) {
    if (slug == CHANNELS[i].slug) {
      Serial.printf("MQTT command: %s\n", CHANNELS[i].name);
      bool ok = sendGateCommand(CHANNELS[i].cmd);
      Serial.println(ok ? "  sent OK" : "  FAILED");
      return;
    }
  }
}

void mqttReconnect() {
  // Resolve a .local hostname via mDNS each time (no static IP / DHCP
  // reservation needed on the router).
  IPAddress host;
  String hostStr(MQTT_HOST);
  if (hostStr.endsWith(".local")) {
    String shortName = hostStr.substring(0, hostStr.length() - 6);
    host = MDNS.queryHost(shortName);
    if (host == IPAddress(0, 0, 0, 0)) {
      Serial.println("mDNS resolve failed, will retry");
      return;
    }
  } else {
    if (!host.fromString(hostStr)) {
      Serial.println("MQTT_HOST is neither a .local name nor a valid IP");
      return;
    }
  }
  mqtt.setServer(host, MQTT_PORT);

  Serial.printf("Connecting to MQTT %s:%d ...\n", host.toString().c_str(), MQTT_PORT);
  bool connected = (strlen(MQTT_USER) > 0)
                        ? mqtt.connect(DEVICE_ID, MQTT_USER, MQTT_PASSWORD, AVAIL_TOPIC, 0, true, "offline")
                        : mqtt.connect(DEVICE_ID, AVAIL_TOPIC, 0, true, "offline");
  if (connected) {
    Serial.println("MQTT connected");
    char sub[96];
    snprintf(sub, sizeof(sub), "%s#", CMD_TOPIC_PREFIX);
    mqtt.subscribe(sub);
    publishHADiscovery();
  } else {
    Serial.printf("MQTT connect failed, rc=%d\n", mqtt.state());
  }
}

