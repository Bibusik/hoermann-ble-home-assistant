// Hoermann SupraMatic (BlueSecur BLE) <-> MQTT bridge for Home Assistant.
// Seeed XIAO ESP32-C3.
//
// Protocol reverse-engineered from the official BlueSecur Android app
// (Hoermann.BleApp.Core / SAL.BlueConnect.IO.{Signed,Encrypted}):
//   - One-time key registration: random 32-byte key, RSA(PKCS#1 v1.5)-
//     encrypted with the gate's own public key (printed as a QR code on the
//     drive), delivered over BLE. Only accepted while the gate is in its
//     own "BLE pairing" window (menu 19 -> BLE on the drive's own panel).
//   - Every command after that: HMAC-SHA256(key, header+payload+challenge),
//     where "challenge" is an 8-byte rolling token the gate hands out on
//     every notification.
// See C:\Users\serge\HoermannBLE\ for the PC-side research/PoC this was
// ported from.

