// ---------------------------------------------------------------------------
// Gate identity (found by BLE sniffing in the PC-side research phase)
// ---------------------------------------------------------------------------
static const char *GATE_ADDR = "e5:9b:6b:d2:84:d9";
static const int GATE_ADDR_TYPE = BLE_ADDR_RANDOM;
static const char *SERVICE_UUID = "669a9001-0008-968f-e311-6050405558b3";
static const char *NOTIFY_UUID = "669a900a-0008-968f-e311-6050405558b3";
static const char *WRITE_UUID = "669a900c-0008-968f-e311-6050405558b3";

// BlueConnect "Signed" command IDs (low 16 bits of DeviceAction, from the
// decompiled DeviceAction enum). All identified by pressing each Home
// Assistant button once and watching the gate: CHANNEL_1=Impuls, CHANNEL_2=
// Light (19/19 isolated captures), CHANNEL_3=Open Partial (1/2), CHANNEL_4=
// Open, CHANNEL_5=Close, CHANNEL_6=Ventilation Position.
enum GateCommand : uint16_t {
  CMD_REGISTER_ROOT = 0x0001,
  CMD_CHANNEL_1 = 0x0011,
  CMD_CHANNEL_2_LIGHT = 0x0012,
  CMD_CHANNEL_3 = 0x0013,
  CMD_CHANNEL_4 = 0x0014,
  CMD_CHANNEL_5 = 0x0015,
  CMD_CHANNEL_6 = 0x0016,
};

// SignedNotificationType values actually used here (from the decompiled
// SAL.BlueConnect.IO.Signed.SignedNotificationType enum).
static const uint16_t NOTIF_TYPE_GATE_STATE = 1;
static const uint16_t NOTIF_TYPE_ROOT_KEY = 2;
static const uint16_t NOTIF_TYPE_ENABLED = 4;
static const uint16_t NOTIF_TYPE_SECURITY_ERROR = 65284;  // 0xFF04

