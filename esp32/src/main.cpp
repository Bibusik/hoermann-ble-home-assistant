uint16_t gRootId = 0;
bool gHaveKey = false;

std::vector<uint8_t> gNotifyBuf;  // reassembled BLE notification bytes for the current connection

mbedtls_entropy_context gEntropy;
mbedtls_ctr_drbg_context gCtrDrbg;

// ---------------------------------------------------------------------------
// Crypto helpers
// ---------------------------------------------------------------------------
void cryptoInit() {
  mbedtls_entropy_init(&gEntropy);
  mbedtls_ctr_drbg_init(&gCtrDrbg);
  const char *pers = "hoermann_bridge";
  mbedtls_ctr_drbg_seed(&gCtrDrbg, mbedtls_entropy_func, &gEntropy,
                         (const unsigned char *)pers, strlen(pers));
}

// RSA-PKCS#1v1.5 encrypt `data` with the gate's public key (DER SubjectPublicKeyInfo).
bool rsaEncryptWithGatePubkey(const uint8_t *data, size_t dataLen, uint8_t *out, size_t *outLen) {
  mbedtls_pk_context pk;
  mbedtls_pk_init(&pk);
  int rc = mbedtls_pk_parse_public_key(&pk, GATE_PUBKEY_DER, GATE_PUBKEY_DER_LEN);
  if (rc != 0) {
    Serial.printf("mbedtls_pk_parse_public_key failed: -0x%04x\n", -rc);
    mbedtls_pk_free(&pk);
    return false;
  }
  mbedtls_rsa_context *rsa = mbedtls_pk_rsa(pk);
  mbedtls_rsa_set_padding(rsa, MBEDTLS_RSA_PKCS_V15, MBEDTLS_MD_NONE);

  rc = mbedtls_rsa_pkcs1_encrypt(rsa, mbedtls_ctr_drbg_random, &gCtrDrbg,
                                  dataLen, data, out);
  if (rc != 0) {
    Serial.printf("mbedtls_rsa_pkcs1_encrypt failed: -0x%04x\n", -rc);
    mbedtls_pk_free(&pk);
    return false;
  }
  *outLen = mbedtls_rsa_get_len(rsa);  // 256 for the gate's 2048-bit key, confirmed against the real device
  mbedtls_pk_free(&pk);
  return true;
}

void hmacSha256(const uint8_t *key, size_t keyLen,
                const uint8_t *msg1, size_t len1,
                const uint8_t *msg2, size_t len2,
                uint8_t out[32]) {
  mbedtls_md_context_t ctx;
  mbedtls_md_init(&ctx);
  mbedtls_md_setup(&ctx, mbedtls_md_info_from_type(MBEDTLS_MD_SHA256), 1);
  mbedtls_md_hmac_starts(&ctx, key, keyLen);
  mbedtls_md_hmac_update(&ctx, msg1, len1);
  if (msg2 && len2) mbedtls_md_hmac_update(&ctx, msg2, len2);
  mbedtls_md_hmac_finish(&ctx, out);
  mbedtls_md_free(&ctx);
}

// Builds one full "Signed" frame: [1][len16][RootId16][Command16][InnerLen16][payload][hmac32]
// matching SignedCommandBase.Serialize() / SignedWriter in the decompiled app.
std::vector<uint8_t> buildSignedFrame(uint16_t rootId, uint16_t command,
                                       const uint8_t *payload, size_t payloadLen,
                                       const uint8_t *key /* 32 bytes */,
                                       const uint8_t *challenge /* 8 bytes */) {
  uint16_t innerLen = 6 + payloadLen + 32;
  std::vector<uint8_t> message;
  message.reserve(6 + payloadLen);
  message.push_back(rootId & 0xFF);
  message.push_back(rootId >> 8);
  message.push_back(command & 0xFF);
  message.push_back(command >> 8);
  message.push_back(innerLen & 0xFF);
  message.push_back(innerLen >> 8);
  message.insert(message.end(), payload, payload + payloadLen);

  uint8_t sig[32];
  hmacSha256(key, 32, message.data(), message.size(), challenge, 8, sig);

  std::vector<uint8_t> inner = message;
  inner.insert(inner.end(), sig, sig + 32);

  uint16_t outerLen = inner.size() + 3;
  std::vector<uint8_t> outer;
  outer.reserve(outerLen);
  outer.push_back(1);
  outer.push_back(outerLen & 0xFF);
  outer.push_back(outerLen >> 8);
  outer.insert(outer.end(), inner.begin(), inner.end());
  return outer;
}

std::vector<uint8_t> buildRegisterRootCmd(uint16_t rootId, const uint8_t *key, const uint8_t *challenge,
                                           const char *username = "ArnoNym") {
  uint8_t payload[17] = {0};  // [0x00][16-byte username, NUL-padded]
  size_t n = strlen(username);
  if (n > 16) n = 16;
  memcpy(payload + 1, username, n);
  return buildSignedFrame(rootId, CMD_REGISTER_ROOT, payload, sizeof(payload), key, challenge);
}

std::vector<uint8_t> buildSwitchRelaisCmd(uint16_t rootId, uint16_t channelCmd,
                                           const uint8_t *key, const uint8_t *challenge) {
  uint64_t ts = (uint64_t)time(nullptr);  // ROOT_KEY path: just an 8-byte UTC-seconds clock value
  uint8_t payload[8];
  memcpy(payload, &ts, 8);  // little-endian on this MCU, matches the frame's own LE fields
  return buildSignedFrame(rootId, channelCmd, payload, sizeof(payload), key, challenge);
}

// ---------------------------------------------------------------------------
// BLE
// ---------------------------------------------------------------------------
void onGateNotify(NimBLERemoteCharacteristic *, uint8_t *data, size_t len, bool) {
  gNotifyBuf.insert(gNotifyBuf.end(), data, data + len);
}

// Signed-channel notification layout (SignedReader.ReadPackage):
//   outer: [1][len_lo][len_hi]
//   inner: [8-byte challenge][2-byte SignedNotificationType][2-byte ...]
// EVERY type=1 (outer) notification carries a fresh challenge, but which ONE
// is valid to sign with depends on context - e.g. the plain ENABLED (4)
// notification sent right on connect is NOT interchangeable with others.
// wantInnerType<0 accepts any inner type (used for ordinary signed-command
// challenges); EncryptedIO's type=2 progress frames never match here.
bool extractChallenge(uint8_t out[8], int wantInnerType = -1) {
  if (gNotifyBuf.size() < 13 || gNotifyBuf[0] != 1) return false;
  uint16_t innerType = gNotifyBuf[11] | (gNotifyBuf[12] << 8);
  if (wantInnerType >= 0 && innerType != (uint16_t)wantInnerType) return false;
  memcpy(out, gNotifyBuf.data() + 3, 8);
  return true;
}

bool bleWriteChunks(NimBLERemoteCharacteristic *writeChar, const std::vector<uint8_t> &blob,
                     bool withResponse = true) {
  for (size_t i = 0; i < blob.size(); i += 20) {
    size_t n = std::min((size_t)20, blob.size() - i);
    if (!writeChar->writeValue(blob.data() + i, n, withResponse)) {
      Serial.println("  BLE write chunk failed");
      return false;
    }
  }
  return true;
}

// Connects, waits for a fresh challenge. Returns null on failure.
NimBLEClient *bleConnectAndGetChallenge(NimBLERemoteCharacteristic **outNotify,
                                         NimBLERemoteCharacteristic **outWrite,
                                         uint8_t challengeOut[8]) {
  NimBLEClient *client = NimBLEDevice::createClient();
  NimBLEAddress addr(GATE_ADDR, GATE_ADDR_TYPE);
  if (!client->connect(addr)) {
    Serial.println("BLE connect failed");
    NimBLEDevice::deleteClient(client);
    return nullptr;
  }
  NimBLERemoteService *svc = client->getService(SERVICE_UUID);
  if (!svc) {
    Serial.println("Service not found");
    client->disconnect();
    NimBLEDevice::deleteClient(client);
    return nullptr;
  }
  NimBLERemoteCharacteristic *notifyChar = svc->getCharacteristic(NOTIFY_UUID);
  NimBLERemoteCharacteristic *writeChar = svc->getCharacteristic(WRITE_UUID);
  if (!notifyChar || !writeChar) {
    Serial.println("Characteristic not found");
    client->disconnect();
    NimBLEDevice::deleteClient(client);
    return nullptr;
  }
  gNotifyBuf.clear();
  notifyChar->subscribe(true, onGateNotify);

  bool ok = false;
  for (int i = 0; i < 10 && !ok; i++) {
    delay(200);
    ok = extractChallenge(challengeOut);
  }
  if (!ok) {
    Serial.println("No challenge received");
    client->disconnect();
    NimBLEDevice::deleteClient(client);
    return nullptr;
  }
  *outNotify = notifyChar;
  *outWrite = writeChar;
  return client;
}

// One-time: register our own root key. The gate must be in its BLE pairing
// window (its own panel: menu 19 -> 02 BLE -> P, then the Bluetooth button).
//
// Mirrors the PC-side PoC exactly (reverse engineered by sniffing a real
// phone registration, then matched against the decompiled app):
//  1. RSA-deliver a random 32-byte key via EncryptedIO (no challenge needed).
//  2. Wait for the EncryptedIO progress frame to reach step=2 ("02 04 00 02
//     ...") - step going 01 -> 03 (never 02) means this connection attempt
//     is dead; the real app abandons it too and just retries on a FRESH
//     connection (no power-cycle needed).
//  3. The INSTANT step=2 is seen, send RegisterRootCmd signed with the
//     connection's ORIGINAL (ENABLED-type) challenge - not a later one.
//  4. A real success is a 3-chunk ROOT_KEY notification (~60 bytes). Its
//     payload is [2-byte assigned RootId][32-byte key XORed against ours] -
//     un-XOR it to get the actual operational key.
bool registerNewRootKey() {
  Serial.println("Registering a new root key (gate must be in BLE pairing mode)...");

  uint8_t newKey[32];
  for (int i = 0; i < 32; i++) newKey[i] = (uint8_t)esp_random();

  uint8_t encKey[256];
  size_t encLen = 0;
  if (!rsaEncryptWithGatePubkey(newKey, 32, encKey, &encLen)) return false;

  std::vector<uint8_t> regBlob;
  uint16_t regLen = encLen + 3;
  regBlob.push_back(2);
  regBlob.push_back(regLen & 0xFF);
  regBlob.push_back(regLen >> 8);
  regBlob.insert(regBlob.end(), encKey, encKey + encLen);

  bool ok = false;
  for (int outerAttempt = 0; outerAttempt < 5 && !ok; outerAttempt++) {
    Serial.printf("--- registration connection attempt %d ---\n", outerAttempt + 1);

    NimBLEClient *client = NimBLEDevice::createClient();
    NimBLEAddress addr(GATE_ADDR, GATE_ADDR_TYPE);
    if (!client->connect(addr)) {
      Serial.println("  BLE connect failed");
      NimBLEDevice::deleteClient(client);
      delay(500);
      continue;
    }
    NimBLERemoteService *svc = client->getService(SERVICE_UUID);
    NimBLERemoteCharacteristic *notifyChar = svc ? svc->getCharacteristic(NOTIFY_UUID) : nullptr;
    NimBLERemoteCharacteristic *writeChar = svc ? svc->getCharacteristic(WRITE_UUID) : nullptr;
    if (!notifyChar || !writeChar) {
      Serial.println("  service/characteristic not found");
      client->disconnect();
      NimBLEDevice::deleteClient(client);
      delay(500);
      continue;
    }
    gNotifyBuf.clear();
    notifyChar->subscribe(true, onGateNotify);

    uint8_t initialChallenge[8];
    bool haveInitial = false;
    for (int i = 0; i < 10 && !haveInitial; i++) {
      delay(100);
      haveInitial = extractChallenge(initialChallenge, NOTIF_TYPE_ENABLED);
    }
    if (!haveInitial) {
      Serial.println("  no initial challenge, retrying...");
      client->disconnect();
      NimBLEDevice::deleteClient(client);
      delay(500);
      continue;
    }

    Serial.println("  sending RSA registration blob...");
    gNotifyBuf.clear();
    bleWriteChunks(writeChar, regBlob);

    Serial.println("  waiting for EncryptedIO progress step=2 (up to ~22s)...");
    bool gotStep2 = false;
    size_t scanned = 0;
    for (int i = 0; i < 110 && !gotStep2; i++) {  // up to ~22s
      delay(200);
      // Each progress notification is its own 20-byte chunk: [2][04][00][step][...].
      // gNotifyBuf just accumulates raw bytes in order, so walk it 20 bytes at a time.
      for (; scanned + 4 <= gNotifyBuf.size(); scanned += 20) {
        if (gNotifyBuf[scanned] == 2 && gNotifyBuf[scanned + 3] == 2) {
          gotStep2 = true;
          break;
        }
      }
    }
    if (!gotStep2) {
      Serial.println("  step=2 never arrived this connection, abandoning (no power-cycle needed)");
      client->disconnect();
      NimBLEDevice::deleteClient(client);
      delay(500);
      continue;
    }
    Serial.println("  got step=2, sending RegisterRoot immediately with the initial challenge...");

    gNotifyBuf.clear();
    auto frame = buildRegisterRootCmd(0, newKey, initialChallenge);  // RootId=0 for this bootstrap frame only
    // Write-without-response here: the device seems to disconnect very soon
    // after step=2, and NimBLE's per-chunk ack round-trip (write-with-response)
    // was sometimes too slow to get all 3 chunks out in time ("BLE write
    // chunk failed" after the link dropped mid-send).
    bleWriteChunks(writeChar, frame, false);

    bool isError = false;
    for (int i = 0; i < 30; i++) {  // up to 3s
      delay(100);
      if (gNotifyBuf.size() >= 13 && gNotifyBuf[11] == 4 && gNotifyBuf[12] == 0xFF) {
        isError = true;
        break;
      }
      if (gNotifyBuf.size() >= 55) break;
    }
    Serial.printf("  RegisterRoot response: %u bytes (%s)\n", (unsigned)gNotifyBuf.size(),
                  isError ? "SECURITY_ERROR" : "...");

    if (gNotifyBuf.size() >= 55 && !isError) {
      // ROOT_KEY notification inner payload (after the 8-byte challenge +
      // 2-byte type + 2-byte discarded field already skipped by our offset):
      // [2-byte RootId][32-byte key XORed against newKey].
      uint16_t assignedRootId = gNotifyBuf[15] | (gNotifyBuf[16] << 8);
      uint8_t finalKey[32];
      for (int i = 0; i < 32; i++) finalKey[i] = gNotifyBuf[17 + i] ^ newKey[i];

      memcpy(gRootKey, finalKey, 32);
      gRootId = assignedRootId;
      prefs.begin("hoermann", false);
      prefs.putBytes("rootkey", gRootKey, 32);
      prefs.putUShort("rootid", gRootId);
      prefs.end();
      gHaveKey = true;
      Serial.printf("New root key registered and saved to flash (RootId=%u).\n", gRootId);
      ok = true;
    }

    client->disconnect();
    NimBLEDevice::deleteClient(client);
    if (!ok) delay(500);
  }

  if (!ok) {
    Serial.println("Registration failed after several fresh-connection retries. "
                    "If this keeps happening, power-cycle the gate and re-open BLE pairing mode.");
  }
  return ok;
}

bool sendGateCommand(uint16_t channelCmd) {
  if (!gHaveKey) {
    Serial.println("No root key yet - publish to .../cmd/register first.");
    return false;
  }
  NimBLERemoteCharacteristic *notifyChar, *writeChar;
  uint8_t challenge[8];
  NimBLEClient *client = bleConnectAndGetChallenge(&notifyChar, &writeChar, challenge);
  if (!client) return false;

  gNotifyBuf.clear();
  auto frame = buildSwitchRelaisCmd(gRootId, channelCmd, gRootKey, challenge);
  bool ok = bleWriteChunks(writeChar, frame);
  delay(500);  // let any ack notification arrive before we tear the link down

  client->disconnect();
  NimBLEDevice::deleteClient(client);
  return ok;
}

