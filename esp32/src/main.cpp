// Arduino entry points
// ---------------------------------------------------------------------------
void setup() {
  Serial.begin(115200);
  delay(500);
  Serial.println("\nHoermann BLE<->MQTT bridge starting");

  cryptoInit();

  prefs.begin("hoermann", true);
  if (prefs.getBytesLength("rootkey") == 32) {
    prefs.getBytes("rootkey", gRootKey, 32);
    gRootId = prefs.getUShort("rootid", 0);
    gHaveKey = true;
    Serial.printf("Loaded saved root key from flash (RootId=%u).\n", gRootId);
  } else {
    Serial.println("No root key saved yet - use the 'register' MQTT button "
                    "while the gate is in BLE pairing mode.");
  }
  prefs.end();

  NimBLEDevice::init("hoermann-bridge");

  WiFi.mode(WIFI_STA);

  Serial.println("Scanning for WiFi networks...");
  int n = WiFi.scanNetworks();
  bool sawTarget = false;
  for (int i = 0; i < n; i++) {
    String ssid = WiFi.SSID(i);
    Serial.printf("  [%2d] rssi=%4d ch=%2d enc=%d  %s%s\n", i, WiFi.RSSI(i), WiFi.channel(i),
                  (int)WiFi.encryptionType(i), ssid.c_str(),
                  ssid == WIFI_SSID ? "   <-- target" : "");
    if (ssid == WIFI_SSID) sawTarget = true;
  }
  if (!sawTarget) {
    Serial.println("WARNING: target SSID was not seen in the scan at all "
                    "(out of range, 5GHz-only band, or hidden network).");
  }

  WiFi.begin(WIFI_SSID, WIFI_PASSWORD);
  Serial.printf("Connecting to WiFi '%s'", WIFI_SSID);
  uint32_t wifiStart = millis();
  while (WiFi.status() != WL_CONNECTED && millis() - wifiStart < 20000) {
    delay(300);
    Serial.print(".");
  }
  if (WiFi.status() != WL_CONNECTED) {
    Serial.printf("\nWiFi FAILED to connect, status=%d. Will keep retrying in the background.\n",
                  (int)WiFi.status());
  } else {
    Serial.printf("\nWiFi connected, IP=%s\n", WiFi.localIP().toString().c_str());
  }

  MDNS.begin("hoermann-bridge");

  // Keep the system clock roughly right - ROOT_KEY-signed commands embed a
  // UTC timestamp; wait briefly for it rather than sending a 1970 epoch.
  configTime(0, 0, "pool.ntp.org", "time.nist.gov");
  Serial.print("Waiting for NTP time sync");
  time_t now = time(nullptr);
  uint32_t ntpStart = millis();
  while (now < 1700000000 && millis() - ntpStart < 8000) {
    delay(300);
    Serial.print(".");
    now = time(nullptr);
  }
  Serial.println(now >= 1700000000 ? " ok" : " timed out (continuing anyway)");

  mqtt.setCallback(onMqttMessage);
}

void loop() {
  if (WiFi.status() != WL_CONNECTED) {
    delay(1000);
    return;
  }
  if (!mqtt.connected()) {
    static uint32_t lastAttempt = 0;
    if (millis() - lastAttempt > 5000) {
      lastAttempt = millis();
      mqttReconnect();
    }
  } else {
    mqtt.loop();
  }

  if (gRegisterRequested) {
    gRegisterRequested = false;
    registerNewRootKey();
  }
}
