"""
PlatformIO pre-build script: reads the two local-only secret files and
generates include/secrets_generated.h, so no credential or key material
ever needs to be typed into chat or committed anywhere.

Inputs (plain text, created by the user, never read aloud by Claude):
  C:\\Users\\serge\\HoermannBLE\\secret\\qr_code.txt       - the gate's QR code text
  C:\\Users\\serge\\HoermannBLE\\secret\\wifi_mqtt.txt     - WIFI_SSID=... etc.
"""
import base64
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

QR_FILE = r"C:\Users\serge\HoermannBLE\secret\qr_code.txt"
WIFI_FILE = r"C:\Users\serge\HoermannBLE\secret\wifi_mqtt.txt"
# PlatformIO execs this file via SCons (no __file__ in that context), so
# derive the path from the project dir it gives us instead.
OUT_FILE = os.path.join(env["PROJECT_DIR"], "include", "secrets_generated.h")  # noqa: F821


def parse_qr(qr_text: str):
    qr_text = qr_text.strip()
    version = int(qr_text[0:2], 16)
    pos = 6
    if version == 1:
        pos += 3 + 2 + 2 + 7
        registration_key = qr_text[pos:]
    elif version in (2, 3, 4):
        pos += 7 + 2 + 2 + 5 + 7
        if version in (3, 4):
            pos += 2
        registration_key = qr_text[pos:] if version != 4 else ""
    else:
        raise ValueError(f"Unknown QR version {version}")
    return registration_key


def parse_kv(path):
    kv = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            kv[k.strip()] = v.strip()
    return kv


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_byte_array(name: str, data: bytes) -> str:
    items = ", ".join(f"0x{b:02x}" for b in data)
    return f"const uint8_t {name}[] = {{{items}}};\nconst size_t {name}_LEN = {len(data)};\n"


def main():
    os.makedirs(os.path.dirname(OUT_FILE), exist_ok=True)

    with open(QR_FILE, "r", encoding="utf-8") as f:
        qr_text = f.read()
    reg_key_b64 = parse_qr(qr_text)
    pubkey_der = base64.b64decode(reg_key_b64)

    wifi = parse_kv(WIFI_FILE)
    required = ["WIFI_SSID", "WIFI_PASSWORD", "MQTT_HOST"]
    missing = [k for k in required if not wifi.get(k)]
    if missing:
        raise SystemExit(
            f"wifi_mqtt.txt is missing values for: {', '.join(missing)}. "
            f"Fill in {WIFI_FILE} and rebuild."
        )

    lines = [
        "// AUTO-GENERATED by gen_secrets.py - do not edit, do not commit.",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        f"#define WIFI_SSID {c_string(wifi['WIFI_SSID'])}",
        f"#define WIFI_PASSWORD {c_string(wifi['WIFI_PASSWORD'])}",
        f"#define MQTT_HOST {c_string(wifi['MQTT_HOST'])}",
        f"#define MQTT_PORT {wifi.get('MQTT_PORT') or '1883'}",
        f"#define MQTT_USER {c_string(wifi.get('MQTT_USER', ''))}",
        f"#define MQTT_PASSWORD {c_string(wifi.get('MQTT_PASSWORD', ''))}",
        "",
        c_byte_array("GATE_PUBKEY_DER", pubkey_der),
    ]

    with open(OUT_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print(f"gen_secrets.py: wrote {OUT_FILE} ({len(pubkey_der)}-byte RSA pubkey, "
          f"wifi SSID len={len(wifi['WIFI_SSID'])})")


main()
